function cardsOf(key) {
  return CARDS.filter(function (c) {
    return key === 'major' ? c.arcana === 'major' : c.suit === key;
  });
}

/* 今日一抽：只从 22 张大阿尔卡纳中抽 */
function drawMajor() {
  var pool = CARDS.filter(function (c) { return c.arcana === 'major'; });
  var c = pool[Math.floor(Math.random() * pool.length)];
  return Object.assign({}, c, { reversed: Math.random() < 0.32 });
}

/* 兼容旧调用：等同于 drawMajor */
function drawOne() { return drawMajor(); }

/* 抽 n 张不重复（全 78 张牌池） */
function drawMany(n) {
  var pool = CARDS.slice(), out = [];
  for (var i = 0; i < n && pool.length; i++) {
    var k = Math.floor(Math.random() * pool.length);
    out.push(Object.assign({}, pool.splice(k, 1)[0], { reversed: Math.random() < 0.32 }));
  }
  return out;
}

/* 三张牌阵综合论断 */
function summaryOf(cards) {
  var up = cards.filter(function (c) { return !c.reversed; }).length;
  var total = cards.length;
  if (up === total) {
    return { level: '大吉', text: '三张全正位，局势在你这边。已经想清楚的事这周就推进，别再反复论证了。' };
  }
  if (up >= Math.ceil(total / 2)) {
    return { level: '小吉', text: '整体向好，但有一处需要你主动处理——重点看逆位那张牌的卡点。' };
  }
  if (up > 0) {
    return { level: '平', text: '阻力略大于助力。别硬推，先解决逆位牌指出的卡点，再谈进度。' };
  }
  return { level: '凶', text: '全逆位。今天适合躺平和复盘，不建议做任何重大决定——包括退学。' };
}

